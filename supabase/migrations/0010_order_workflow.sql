-- Dapa Home — flujo de estados de pedidos y panel admin
-- Ejecutar en Supabase SQL Editor ANTES de desplegar el código que lo usa.

alter table public.orders add column if not exists payment_status text not null default 'pending';
alter table public.orders add column if not exists admin_notes text;
alter table public.orders add column if not exists order_number bigint generated by default as identity;

create unique index if not exists orders_order_number_idx on public.orders(order_number);

-- Los estados antiguos (pending/paid/failed/cancelled) pasan al nuevo flujo.
alter table public.orders drop constraint if exists orders_status_check;

update public.orders set
  payment_status = case status when 'paid' then 'paid' when 'failed' then 'failed' else 'pending' end,
  status = case status
    when 'pending' then 'recibido'
    when 'paid' then 'pagado'
    when 'failed' then 'recibido'
    when 'cancelled' then 'cancelado'
    else status
  end
where status in ('pending', 'paid', 'failed', 'cancelled');

alter table public.orders alter column status set default 'recibido';
alter table public.orders add constraint orders_status_check check (
  status in ('recibido', 'pagado', 'en_fabricacion', 'completado', 'enviado', 'entregado', 'cancelado')
);
alter table public.orders drop constraint if exists orders_payment_status_check;
alter table public.orders add constraint orders_payment_status_check check (
  payment_status in ('pending', 'paid', 'failed')
);

create index if not exists orders_payment_status_idx on public.orders(payment_status);

-- El admin autenticado puede cambiar estado y notas (la creación sigue siendo sólo desde el servidor).
drop policy if exists "orders admin update" on public.orders;
create policy "orders admin update" on public.orders
  for update using (public.is_admin()) with check (public.is_admin());
